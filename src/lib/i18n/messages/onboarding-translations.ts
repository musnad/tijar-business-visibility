const localeStrings = { en, ha, yo, ig, ar, sw, ff };

export function getOnboardingTranslationOverlay(locale: Locale): MessageTree {
  const key = locale in localeStrings ? (locale as keyof typeof localeStrings) : "en";
  const strings = localeStrings[key];
  return deepMergeMessages(
    appBlock(strings) as MessageTree,
    optionsFor(key) as MessageTree,
  );
}

function deepMergeMessages(base: MessageTree, overlay: MessageTree): MessageTree {
  const result: MessageTree = { ...base };
  for (const k of Object.keys(overlay)) {
    const b = base[k];
    const o = overlay[k];
    if (o && typeof o === "object" && b && typeof b === "object") {
      result[k] = deepMergeMessages(b as MessageTree, o as MessageTree);
    } else if (o !== undefined) {
      result[k] = o;
    }
  }
  return result;
}
